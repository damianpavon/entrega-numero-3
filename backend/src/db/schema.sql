-- =====================================================================
-- Esquema PostgreSQL - Carta Digital PNK Security
-- Migrado desde MySQL (legacy/Script_BD/pnk_security.sql).
-- Es IDEMPOTENTE: se puede ejecutar en cada arranque sin perder datos.
-- Cambios respecto al original:
--   * AUTO_INCREMENT -> GENERATED ... AS IDENTITY
--   * bit(1)         -> boolean
--   * datetime       -> timestamptz
--   * "restautantes" (typo) -> "restaurantes"
--   * usuarios.password (texto plano) -> usuarios.password_hash (bcrypt)
-- =====================================================================

CREATE TABLE IF NOT EXISTS direcciones (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calle       varchar(100) NOT NULL,
  numero      varchar(15)  NOT NULL,
  comuna      varchar(100) NOT NULL,
  region      varchar(100),
  creado      timestamptz DEFAULT now(),
  actualizado timestamptz,
  eliminado   timestamptz
);

CREATE TABLE IF NOT EXISTS restaurantes (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rut            varchar(11)  NOT NULL,
  nombre         varchar(200) NOT NULL,
  fono           varchar(45)  NOT NULL,
  mapa           varchar(200),
  foto           varchar(200),
  email          varchar(100),
  creado         timestamptz DEFAULT now(),
  actualizado    timestamptz,
  eliminado      timestamptz,
  direcciones_id integer NOT NULL REFERENCES direcciones(id)
);

CREATE TABLE IF NOT EXISTS cartas (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          varchar(45),
  orden           integer,
  visible         boolean DEFAULT TRUE,
  foto            varchar(200),
  creada          timestamptz DEFAULT now(),
  actualizada     timestamptz,
  eliminada       timestamptz,
  restaurantes_id integer NOT NULL REFERENCES restaurantes(id)
);

CREATE TABLE IF NOT EXISTS categorias (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      varchar(100) NOT NULL,
  visible     boolean DEFAULT FALSE,
  foto        varchar(200),
  orden       integer,
  creado      timestamptz DEFAULT now(),
  actualizado timestamptz,
  eliminado   timestamptz,
  cartas_id   integer NOT NULL REFERENCES cartas(id)
);

CREATE TABLE IF NOT EXISTS items (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(100) NOT NULL,
  descripcion   varchar(300),
  tiempo        varchar(100),
  observaciones varchar(300),
  precio        integer CHECK (precio IS NULL OR precio >= 0),
  visible       boolean DEFAULT FALSE,
  destacado     boolean DEFAULT FALSE,
  puntuacion    integer DEFAULT 0 CHECK (puntuacion BETWEEN 0 AND 5),
  foto          varchar(200),
  orden         integer,
  creado        timestamptz DEFAULT now(),
  actualizado   timestamptz,
  eliminado     timestamptz,
  categorias_id integer NOT NULL REFERENCES categorias(id)
);

CREATE TABLE IF NOT EXISTS usuarios (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(255) NOT NULL,
  email         varchar(255) NOT NULL UNIQUE,
  password_hash varchar(100) NOT NULL,          -- bcrypt, nunca texto plano
  estado        boolean NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS comentarios (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      integer REFERENCES usuarios(id),
  usuario         varchar(255) NOT NULL,
  comentario      text NOT NULL CHECK (char_length(comentario) <= 1000),
  restaurantes_id integer NOT NULL REFERENCES restaurantes(id),
  creado          timestamptz DEFAULT now()
);

-- Tabla de sesiones (connect-pg-simple). Sesiones en BD => funcionan con
-- varias instancias detrás del Load Balancer / Autoscaling de AWS.
CREATE TABLE IF NOT EXISTS sesiones (
  sid    varchar NOT NULL PRIMARY KEY,
  sess   json    NOT NULL,
  expire timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sesiones_expire ON sesiones (expire);

-- Índices de las consultas de la carta
CREATE INDEX IF NOT EXISTS idx_cartas_restaurante  ON cartas (restaurantes_id);
CREATE INDEX IF NOT EXISTS idx_categorias_carta    ON categorias (cartas_id);
CREATE INDEX IF NOT EXISTS idx_items_categoria     ON items (categorias_id);
CREATE INDEX IF NOT EXISTS idx_comentarios_resto   ON comentarios (restaurantes_id);
